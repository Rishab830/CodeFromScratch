const { chromium } = require('@playwright/test');
const assert = require('node:assert/strict');
const fs = require('node:fs');

(async () => {
  const browser = await chromium.launch({ channel: 'chrome', headless: true });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1050 } });
  const page = await context.newPage();
  page.on('pageerror', (error) => console.log('PAGE ERROR', error.message));
  await page.goto(process.env.TEST_URL || 'http://localhost:3000');
  await page.waitForSelector('.cm-content', { timeout: 45000 });
  await page.waitForFunction(() => {
    const line = document.querySelector('.editable-line');
    const editor = document.querySelector('.editor-body');
    if (!line || !editor) return false;
    const a = line.getBoundingClientRect(), b = editor.getBoundingClientRect();
    return a.top >= b.top && a.bottom <= b.bottom;
  }, {timeout: 10000});
  console.log('PASS: editor opens at the editable Python section');
  await page.waitForFunction(() => !document.querySelector('.play-yourself').disabled, { timeout: 150000 });
  console.log('PASS: actual Pygame WASM runtime ready');

  const frame = page.frames().find((frame) => frame.url().includes('/runner/'));
  async function playerPosition() {
    // Read rendered pixel locations, not a simulated JavaScript game state.
    return frame.evaluate(() => {
      const canvas = document.querySelector('#canvas');
      const context = canvas.getContext('2d');
      const {data, width} = context.getImageData(0, 0, canvas.width, canvas.height);
      let sx = 0, sy = 0, count = 0;
      for (let i = 0; i < data.length; i += 4) {
        if (data[i] === 228 && data[i+1] === 109 && data[i+2] === 84) {
          sx += (i / 4) % width; sy += Math.floor((i / 4) / width); count++;
        }
      }
      return {x: sx / count, y: sy / count, count};
    });
  }
  await page.getByRole('button', { name: 'Play yourself', exact: true }).click();
  await page.waitForTimeout(200);
  const before = await playerPosition();
  await page.keyboard.down('ArrowLeft');
  await page.waitForTimeout(450);
  await page.keyboard.up('ArrowLeft');
  const after = await playerPosition();
  assert(after.x < before.x - 30, `Keyboard movement failed: ${JSON.stringify({before,after})}`);
  await page.keyboard.down('Space');
  await page.waitForTimeout(150);
  await page.keyboard.up('Space');
  const jumped = await playerPosition();
  assert(jumped.y < after.y - 15, 'Space did not jump');
  console.log('PASS: browser keyboard movement and jumping affect actual Pygame rendering');

  await page.getByRole('button', { name: /Test my fix/ }).click();
  await page.waitForFunction(() => document.querySelector('.status-pill').textContent === 'TRY AGAIN', {timeout: 15000});
  assert.match(await page.locator('.console-message').innerText(), /jumping/);
  assert(await page.locator('.journey-stop.next').isDisabled());
  console.log('PASS: incorrect Python jumps repeatedly and does not unlock the next level');

  const editor = page.locator('.cm-content');
  // Use CodeMirror's view to send the same transactions generated by typing.
  const getSource = () => editor.evaluate((node) => node.cmTile.root.view.state.doc.toString());
  let source = await getSource();
  await editor.evaluate((node) => node.cmTile.root.view.dispatch({ changes: { from: 0, to: 1, insert: 'X' } }));
  assert.equal(await getSource(), source, 'Protected source was editable');
  console.log('PASS: protected source rejects edit transactions');
  await editor.evaluate((node) => {
    const view = node.cmTile.root.view;
    const text = view.state.doc.toString();
    const from = text.indexOf('    player.jump()\n', text.indexOf('def on_blue'));
    view.dispatch({ changes: {from, to: from + '    player.jump()\n'.length, insert: '    player.move_left(\n'} });
  });
  await page.getByRole('button', { name: /Test my fix/ }).click();
  await page.waitForFunction(() => document.querySelector('.status-pill').textContent === 'TRY AGAIN', {timeout:10000});
  assert.match(await page.locator('.console-message').innerText(), /Python syntax error/);
  console.log('PASS: Python syntax errors appear in the adventure log');
  await editor.evaluate((node) => {
    const view = node.cmTile.root.view;
    const text = view.state.doc.toString();
    const start = text.indexOf('    # EDIT START: fix the action below\n') + '    # EDIT START: fix the action below\n'.length;
    const end = text.indexOf('    # EDIT END', start);
    view.dispatch({ changes: {from: start, to: end, insert: '    player.move_left()\n'} });
  });
  assert.match(await getSource(), /def on_blue\(player\):\n.*\n    player.move_left\(\)/);
  await page.getByRole('button', { name: /Test my fix/ }).click();
  await page.waitForFunction(() => document.querySelector('.status-pill').textContent === 'SOLVED', {timeout: 15000});
  assert.match(await page.locator('.console-message').innerText(), /without jumping/);
  assert(!(await page.locator('.journey-stop.next').isDisabled()));
  assert.match(await page.locator('.xp').innerText(), /100/);
  console.log('PASS: edited Python executes, reaches the flag, grants XP, and unlocks next-level placeholder');
  await page.screenshot({path:'solved.png', fullPage:true});
  await page.getByRole('button', {name:'Next adventure',exact:true}).click();
  await page.getByRole('dialog').waitFor();
  assert.match(await page.getByRole('dialog').innerText(), /one-level demo/);
  await page.getByRole('button',{name:'Close',exact:true}).click();
  await page.getByRole('button',{name:'Play this level again',exact:true}).click();

  await page.getByRole('button',{name:'Reset starter code'}).click();
  await page.waitForFunction(() => {
    const text = document.querySelector('.cm-content').cmTile.root.view.state.doc.toString();
    return text.split('# EDIT START: fix the action below\n')[1].split('# EDIT END')[0].includes('player.jump()');
  });
  const resetSource = await getSource();
  const block = resetSource.split('# EDIT START: fix the action below\n')[1].split('# EDIT END')[0];
  assert.match(block, /player.jump\(\)/, 'Reset did not restore starter Python');
  console.log('PASS: reset restores starter source');
  await page.screenshot({path:'desktop.png',fullPage:true});

  await page.setViewportSize({width:390,height:844});
  await page.waitForTimeout(300);
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth);
  assert.equal(overflow, false, 'Mobile layout overflows horizontally');
  await page.screenshot({path:'mobile.png',fullPage:true});
  console.log('PASS: mobile layout fits viewport');
  await page.getByRole('button',{name:'Play yourself',exact:true}).click();
  await page.waitForTimeout(200);
  const touchBefore = await playerPosition();
  const touchButton = await page.getByRole('button',{name:'Move left',exact:true}).boundingBox();
  await page.mouse.move(touchButton.x + touchButton.width / 2, touchButton.y + touchButton.height / 2);
  await page.mouse.down();
  await page.waitForTimeout(350);
  await page.mouse.up();
  const touchAfter = await playerPosition();
  assert(touchAfter.x < touchBefore.x - 20, `Touch movement failed: ${JSON.stringify({touchBefore,touchAfter})}`);
  console.log('PASS: on-screen movement controls affect Pygame');
  await browser.close();
})().catch((error) => {console.error(error); process.exit(1);});
