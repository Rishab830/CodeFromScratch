const {chromium}=require('@playwright/test');
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path');
const {core}=require('./level-fixtures.cjs');
const {GREENHOUSE_SOLUTION,greenhousePixels,moveGreenhouseGirl,runGreenhouse,exitGreenhouse}=require('./greenhouse-fixture.cjs');
const qa=path.join(__dirname,'..','artifacts','qa');fs.mkdirSync(qa,{recursive:true});
let browser,page;
(async()=>{
  browser=await chromium.launch({channel:'chrome',headless:true});
  page=await browser.newPage({viewport:{width:1440,height:1100}});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.addInitScript(keys=>keys.forEach(key=>localStorage.setItem(key+':complete','yes')),core.map(l=>l.storage));
  await page.goto((process.env.TEST_URL||'http://127.0.0.1:3001')+'/?level=greenhouse-grid');
  await page.getByRole('heading',{name:'The Greenhouse',exact:false}).waitFor();
  await page.getByRole('button',{name:'Play level',exact:true}).waitFor({timeout:180000});
  assert.equal(await page.locator('.touch-controls button').count(),3);
  assert.match(await page.locator('.keyboard-guide').innerText(),/Use lever \/ door/);
  assert((await page.locator('.keyboard-guide').innerText()).includes('\u2190 \u2192 / A D'));
  await page.getByRole('button',{name:'Play level',exact:true}).click();
  await page.keyboard.press('Space');await page.waitForTimeout(450);
  assert.deepEqual((await greenhousePixels(page)).plants,[0,0,0]);
  await moveGreenhouseGirl(page,49);await page.keyboard.press('Space');
  await page.getByRole('dialog',{name:'Game over',exact:true}).waitFor({timeout:20000});
  const starter=await greenhousePixels(page);assert(starter.plants[0]>0&&starter.plants[1]>0);assert.equal(starter.plants[2],0);
  assert.match(await page.locator('.console-message').innerText(),/machine stopped before the greenhouse was ready/);
  assert.equal(await page.evaluate(()=>localStorage.getItem('cfs:coins:level-13:v1')),'["garden","row"]');
  await page.screenshot({path:path.join(qa,'greenhouse-starter-two-plants.png'),fullPage:true});
  console.log('PASS: lever proximity required; starter animates two plants and both coin flights before game over.');
  await page.locator('.cm-content').evaluate((node,body)=>{const view=node.cmTile.root.view,text=view.state.doc.toString(),m=/^[ \t]*# EDIT START\n/m.exec(text),start=m.index+m[0].length,end=start+/^[ \t]*# EDIT END/m.exec(text.slice(start)).index;view.dispatch({changes:{from:start,to:end,insert:body}})},GREENHOUSE_SOLUTION);
  await page.getByRole('button',{name:'Compile',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('.status-pill').textContent==='PLAYING');
  let sawWater=false,sawStages=false,screenshot=false;
  await runGreenhouse(page,async p=>{
    if(p.water)sawWater=true;
    if(p.plants[0]>0&&p.plants[0]<100)sawStages=true;
    if(!screenshot&&p.water&&p.plants[0]>0){screenshot=true;await page.screenshot({path:path.join(qa,'greenhouse-watering-animation.png'),fullPage:true})}
  });
  assert(sawWater&&sawStages,'Water droplets and growing leaves should be visible during the automatic run.');
  assert.equal(await page.getByRole('dialog',{name:'Level complete',exact:true}).count(),0);
  await page.waitForTimeout(800);
  await page.screenshot({path:path.join(qa,'greenhouse-grown-key.png'),fullPage:true});
  await exitGreenhouse(page);
  assert.equal(await page.getByRole('group',{name:'Coins collected: 2 of 2',exact:true}).count(),1);
  assert.equal(await page.evaluate(()=>localStorage.getItem('cfs:bonus:greenhouse:v1:complete')),'yes');
  assert.equal(await page.evaluate(()=>localStorage.getItem('cfs:coins:level-13:v1')),'["garden","row"]');
  await page.screenshot({path:path.join(qa,'greenhouse-complete.png'),fullPage:true});
  await page.setViewportSize({width:390,height:844});assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  assert.equal(errors.length,0,errors.join('\n'));
  console.log('PASS: one lever press runs nested loops; stage growth and rain animate; player picks up key, opens door and walks out; two coins persist.');
})().catch(async error=>{console.error(error);if(page)await page.screenshot({path:path.join(qa,'greenhouse-failure.png'),fullPage:true}).catch(()=>{});process.exitCode=1}).finally(async()=>{if(browser)await browser.close()});
